            # Load the engine spec JSON from file
            url = res.get("url")
            filename = url.split("/")[-1]
            filepath = Path(__file__).parent.parent / "static" / "viz_specs" / filename

            with open(filepath) as f:
                engine_spec = json.load(f)

            # Enforce consistent dimensions for comparison dashboard unless it's a multi-panel layout
