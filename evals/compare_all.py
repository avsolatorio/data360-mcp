def _clean_llm_resolve_block(spec: dict) -> None:
    """Fix common invalid resolve patterns generated by the LLM."""
    if "resolve" not in spec or not isinstance(spec["resolve"], dict):
        return
    res = spec["resolve"]
    for channel in ["x", "y"]:
        if channel in res and isinstance(res[channel], dict):
            for subkey in ["scale", "axis", "legend"]:
                if subkey in res[channel]:
                    val = res[channel][subkey]
                    res.setdefault(subkey, {})
                    res[subkey][channel] = val
                    res[channel].pop(subkey, None)
            if not res[channel]:
                res.pop(channel, None)


def get_engine_y_axis_scale(spec):
    y_encoding = spec.get("encoding", {}).get("y", {})
    # Check layer / spec level
    if not y_encoding and "layer" in spec:
        for layer in spec["layer"]:
            y_encoding = layer.get("encoding", {}).get("y", {})
            if y_encoding:
                break

    if not y_encoding:
        return "Automatic Y-axis scale."

    scale = y_encoding.get("scale", {})
    zero = scale.get("zero")
    domain = scale.get("domain")

    desc = []
    if zero is True:
        desc.append("Zero-baseline (zero: true)")
    elif zero is False:
        desc.append("Zoomed-in (zero: false)")
    else:
        desc.append("Default baseline (auto-fitting)")

    if domain:
        desc.append(f"Domain locked to {domain}")

    return " | ".join(desc)


def get_engine_design_choice(strategy, spec):
    if strategy == "temporal_multi_indicator":
        return "Layers multiple temporal indicators sharing a compatible scale on a single panel. Designed to easily contrast two related variables over time."
    elif strategy == "temporal_single":
        return "Standard time series line chart representing one indicator over time for selected economies. Highlights temporal trends and country differences."
    elif strategy == "small_multiples":
        return "Faceted panels to prevent clutter when viewing multiple dimensions, breakdown categories, or incompatible scales. Keeps Y-axes independent."
    elif strategy == "cross_sectional":
        return "Vertical bar chart sorted descending to compare values of multiple countries in a single year. Focuses on country ranking and magnitude."
    elif strategy == "heatmap":
        return "2D grid colored by intensity to represent values across many countries and years. Ideal for large grids of temporal/spatial data."
    elif strategy == "correlation":
        return "Scatter plot to visualize relationship and correlation between two indicators. Useful for exploring bivariate associations."
    elif strategy == "choropleth":
        return "World map colored by value intensity for geographic comparison of a single indicator across many economies."
    elif strategy == "stacked_area":
        return "Stacked area chart showing composition and cumulative values over time, preserving total proportional context."
    elif strategy == "chained":
        return "Multiple sequential panel charts to walk through complex combinations of multiple indicators, countries, and dimensions."
    return "Rule-based visualization selection based on data profile parameters."


